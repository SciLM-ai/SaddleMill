    displacement_dict=None,
    dimer_control_kwargs=None,
    control_logfile=None,
    mode_logfile=None,
    logfile=None,
    trajectory=None,
    engine="ase",
    min_mode_finder="dimer",
    mmf_variant="standard",
    mode_reuse="none",
    convex_escape="standard",
    bowl_active_atoms=20,
    minmode_options=None,
